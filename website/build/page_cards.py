"""Generate one page card per unit (26) from the ledger, the output manifest and the register.

Usage: python website/build/page_cards.py [--out DIR]     (default DIR: docs/restructure/pages)

Sources, all read-only: docs/restructure/ledger-sections.md (rows), order.md (neighbours, families,
old papers), docs/model-v3/outputs.yml (element lists), inputs.md (register ids), template.md (front matter).
Cards are data: no spoke prose, `question` left blank. Output is deterministic (no dates, sorted keys).
"""
import argparse
import collections
import pathlib
import re
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
LEDGER_SECTIONS = ROOT / 'docs/restructure/ledger-sections.md'
LEDGER = ROOT / 'docs/restructure/ledger.md'
ORDER = ROOT / 'docs/restructure/order.md'
OUTPUTS = ROOT / 'docs/model-v3/outputs.yml'
INPUTS = ROOT / 'docs/model-v3/inputs.md'
DEFAULT_OUT = ROOT / 'docs/restructure/pages'

SPOKES = ['MECH', 'VAL', 'FISC', 'GOV', 'PAY', 'FUND', 'CORP', 'DECL', 'BEHAV', 'FAIR', 'LIT', 'ATTR',
          'WELF', 'FIRST', 'WIDER', 'POL', 'ADOPT', 'PILOT', 'UNCER', 'LIMIT', 'FALS', 'HYPO']
STANDALONE = ['ADD', 'INST', 'SCOPE']
HUB = 'HUB'
UNITS = SPOKES + STANDALONE + [HUB]
HUB_SECTIONS = [f'H{i}' for i in range(8)]
CAP = 6000


def cells(line, n, what):
    c = [x.strip() for x in line.strip().strip('|').split('|')]
    if len(c) != n:
        raise ValueError(f'{what}: expected {n} cells, got {len(c)}: {line[:80]}')
    return c


def num(s):
    return int(s.replace(',', ''))


def read_ledger_rows():
    rows, paper = [], None
    for line in LEDGER_SECTIONS.read_text(encoding='utf-8').splitlines():
        if line.startswith('## '):
            paper = line[3:].strip()
        elif line.startswith('| ') and not line.startswith('| Sec') and not line.startswith('|---'):
            c = cells(line, 8, 'ledger-sections row')
            rows.append(dict(paper=paper, sec=c[0], section=c[1], words=num(c[2]), disp=c[3],
                             target=c[4], model=c[5], demands=c[6], note=c[7]))
    return rows


def table_after(text, heading, ncols):
    """Rows of the first markdown table after a heading line that starts with `heading`."""
    lines = text.splitlines()
    i = next(k for k, l in enumerate(lines) if l.startswith(heading))
    out = []
    for l in lines[i + 1:]:
        if l.startswith('|'):
            if l.startswith('|---') or l.startswith('| Pos') or l.startswith('| Page'):
                continue
            out.append(cells(l, ncols, heading))
        elif out:
            break
    return out


def read_order():
    t = ORDER.read_text(encoding='utf-8')
    order = {}
    for c in table_after(t, '## 2. Order', 6):
        order[c[2]] = dict(pos=c[0], wave=c[1], why=c[3], cites=c[4], cited_by=c[5])
    need = {}
    for c in table_after(t, '## 3. What each page needs', 6):
        need[c[1]] = dict(pos=c[0], outputs=c[2], families=c[3], freeze=c[4], papers=c[5])
    return order, need


def unit_key(name):
    return HUB if name.startswith('Hub') else name


def read_outputs():
    return yaml.safe_load(OUTPUTS.read_text(encoding='utf-8'))['outputs']


def read_register():
    ids = []
    for line in INPUTS.read_text(encoding='utf-8').splitlines():
        m = re.match(r'\|\s*(I-[A-Z]+\d+[a-z0-9]*)\s*\|', line)
        if m:
            ids.append(m.group(1))
    return ids


def family_of(rid):
    return re.match(r'I-([A-Z]+\d+)', rid).group(1)


def expand_families(text):
    """'D1, D4 (x), H1 to H3' -> ['D1','D4','H1','H2','H3']."""
    t = re.sub(r'\([^)]*\)', '', text)
    out = []
    for m in re.finditer(r'\b([A-Z])(\d+)(?:\s+to\s+([A-Z])?(\d+))?', t):
        letter, a, l2, b = m.groups()
        if b:
            out += [f'{letter}{i}' for i in range(int(a), int(b) + 1)]
        else:
            out.append(f'{letter}{a}')
    return sorted(set(out), key=lambda f: (f[0], int(f[1:])))


def pages_of_element(e):
    return HUB if e in HUB_SECTIONS else e


def kept_words(rows, unit):
    mine = [r for r in rows if r['target'] == unit]
    k = sum(r['words'] for r in mine if r['disp'] == 'K')
    m = sum(r['words'] for r in mine if r['disp'] == 'M')
    sa = sum(r['words'] for r in mine if r['disp'] == 'SA')
    return k, m, sa


def cell(s):
    return s.replace('|', '/')


def card(unit, rows, order, need, outputs, register):
    lines = []
    A = lines.append
    title = unit if unit != HUB else 'Hub (H0 to H7)'
    A(f'# Page card: {title}')
    A('')
    A('> Generated by `website/build/page_cards.py` from `ledger-sections.md`, `order.md`, `outputs.yml` and `inputs.md`. '
      'Do not edit by hand; rerun the script. This card holds data only, no spoke prose.')
    A('')
    ok = order.get(unit)
    nd = need.get(unit)
    # outputs
    outs = [o for o in outputs if any(pages_of_element(e) == unit for e in o.get('element', []))]
    out_ids = [o['id'] for o in outs]
    # front matter
    depends = []
    if ok:
        depends = [s for s in SPOKES if re.search(rf'\b{s}\b', ok['cites']) and s != unit]
        if 'all spokes' in ok['cites'] or ok['cites'].strip() == 'all':
            depends = [s for s in SPOKES if s != unit]
    fam = expand_families(nd['families']) if nd else []
    A('## Front matter skeleton')
    A('')
    if unit in SPOKES:
        A('```yaml')
        A('---')
        A(f'spoke: {unit}')
        A('question: ""            # blank: the writer and author set it')
        A('status: draft')
        A(f'budget: {{cap: {CAP}}}')
        A(f'outputs: [{", ".join(out_ids)}]   # the set of outputs.yml entries that list {unit}')
        A('inputs: []             # fixed at drafting from the families below (hooks.md Q7: ids)')
        A(f'depends: [{", ".join(depends)}]')
        A('---')
        A('```')
    else:
        A(f'Not a spoke: the spoke front matter of `template.md` section 2 does not apply to this unit. '
          f'Outputs listing it in `outputs.yml`: {", ".join(out_ids) if out_ids else "none"}.')
    A('')
    # neighbours
    A('## Neighbours (`order.md` sections 2 and 3)')
    A('')
    if ok:
        A(f'- Position {ok["pos"]}, wave {ok["wave"]}')
        A(f'- Why here: {cell(ok["why"])}')
        A(f'- Cites (for substance): {cell(ok["cites"])}')
        A(f'- Cited by: {cell(ok["cited_by"])}')
    else:
        A('- not in `order.md` section 2')
    if nd:
        A(f'- Old papers to read, by section only: {cell(nd["papers"])}')
        A(f'- Data to freeze: {cell(nd["freeze"])}')
    A('')
    # outputs
    A('## Outputs whose `element:` lists this page')
    A('')
    if outs:
        A('| Id | Metric | Title | Kind | Element (all pages) |')
        A('|---|---|---|---|---|')
        for o in outs:
            A(f'| {o["id"]} | {o.get("metric", "")} | {cell(o["title"])} | {o.get("kind", "")} | {", ".join(o["element"])} |')
    else:
        A('None.')
    A('')
    # inputs
    A('## Register input families')
    A('')
    if nd:
        A(f'`order.md` section 3: {cell(nd["families"])}')
    A('')
    byfam = collections.defaultdict(list)
    for rid in register:
        byfam[family_of(rid)].append(rid)
    shown = [f for f in fam if f in byfam]
    if shown:
        for f in shown:
            ids = byfam[f]
            A(f'- **{f}** ({len(ids)} rows): {", ".join(ids)}')
    else:
        A('No register family listed.')
    A('')
    # words
    k, m, sa = kept_words(rows, unit if unit != HUB else None) if unit != HUB else (0, 0, 0)
    hub_rows = [r for r in rows if r['target'] in HUB_SECTIONS]
    mine = hub_rows if unit == HUB else [r for r in rows if r['target'] == unit]
    if unit == HUB:
        k = sum(r['words'] for r in mine if r['disp'] == 'K')
        m = sum(r['words'] for r in mine if r['disp'] == 'M')
    model = collections.Counter()
    for r in mine:
        if r['disp'] in ('K', 'M'):
            model[r['model']] += r['words']
    A('## Words against the cap')
    A('')
    A(f'- Kept (K rows): {k:,}')
    A(f'- Merged (M rows, overlap kept sections, not additional): {m:,}')
    if sa:
        A(f'- Standalone (SA rows): {sa:,}')
    A(f'- Kept words whose claims need model numbers: Y {model["Y"]:,}, P {model["P"]:,} (kept and merged)')
    if unit in SPOKES:
        A(f'- Kept / cap: {k:,} / {CAP:,} = {k / CAP:.2f}')
    elif unit == HUB:
        A('- The 6,000-word cap is a spoke rule; the hub has no cap in `template.md`.')
    else:
        A('- Standalone paper: the 6,000-word spoke cap does not apply.')
    if unit in ('ADOPT', 'PILOT', 'HYPO'):
        A('- The ledger does not yet assign rows to this page: the split of `ledger.md` 9.2 moves them from '
          + ('POL' if unit != 'HYPO' else 'FALS') + ' when the author takes it.')
    A('')
    # ledger rows
    A('## Ledger rows (target = this page)')
    A('')
    shown_rows = [r for r in mine if r['disp'] in ('K', 'M', 'SA')]
    if unit == HUB:
        A('Hub sections H0 to H7. H0 and H3 to H7 draw on spokes and the data layer; no old words are assigned to them.')
        A('')
    if shown_rows:
        A('| Old paper | Sec | Section | Words | Disp | Model | Demands | Note |')
        A('|---|---|---|---:|---|---|---|---|')
        for r in shown_rows:
            A(f'| {cell(r["paper"])} | {cell(r["sec"])} | {cell(r["section"])} | {r["words"]:,} | {r["disp"]} | '
              f'{r["model"]} | {cell(r["demands"])} | {cell(r["note"])} |')
    else:
        A('None.')
    if unit == HUB:
        dl = [r for r in rows if r['target'] in ('UK data pack', 'method note for O7')]
        A('')
        A('Data pages that travel with the hub (DL4 method, DL6 UK data pack): ledger rows with those targets.')
        A('')
        if dl:
            A('| Old paper | Sec | Section | Words | Disp | Target |')
            A('|---|---|---|---:|---|---|')
            for r in dl:
                A(f'| {cell(r["paper"])} | {cell(r["sec"])} | {cell(r["section"])} | {r["words"]:,} | {r["disp"]} | {cell(r["target"])} |')
    A('')
    return '\n'.join(lines)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default=str(DEFAULT_OUT))
    a = ap.parse_args(argv)
    out = pathlib.Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    rows = read_ledger_rows()
    order_raw, need_raw = read_order()
    order = {unit_key(k): v for k, v in order_raw.items()}
    need = {unit_key(k): v for k, v in need_raw.items()}
    missing = [u for u in UNITS if u not in order or u not in need]
    if missing:
        sys.exit(f'units missing from order.md: {missing}')
    outputs = read_outputs()
    register = read_register()
    for u in UNITS:
        (out / f'{u}.md').write_text(card(u, rows, order, need, outputs, register), encoding='utf-8', newline='\n')
    print(f'wrote {len(UNITS)} cards to {out}')


if __name__ == '__main__':
    main()
