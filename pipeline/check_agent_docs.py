"""
check_agent_docs.py: fail on a broken link or named path in the agent guides (brief 075c).

    python -I pipeline/check_agent_docs.py [--root DIR]

Scans AGENTS.md, START_HERE.md, docs/agents/*.md and .claude/skills/*/SKILL.md.
Rules
 1. A markdown link [text](path) must resolve relative to the file that holds it
    (the guides write reference/... relative to docs/agents/). http, mailto and
    pure #anchor links are skipped; for path#anchor only the file is checked.
 2. A backticked token that looks like a repo path (has a "/" and a known
    extension, or ends in "/") must exist, from the repo root or from the file's
    own folder, unless it is on the allow-list below.
 3. Each .claude/skills/<role>/SKILL.md names AGENTS.md and a docs/agents guide,
    and that guide exists.
One line per finding, `file:line message`; exit 1 if any. Standard library only.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

SCAN = ("AGENTS.md", "START_HERE.md", "docs/agents/*.md", ".claude/skills/*/SKILL.md")
EXTS = (".md", ".py", ".toml", ".json", ".yml", ".yaml", ".html", ".bib", ".skill", ".qmd")
LINK = re.compile(r"\[[^\]]*\]\(([^)\s]+)\)")
TICK = re.compile(r"`([^`\s]+)`")
GUIDE = re.compile(r"docs/agents/([\w.-]+\.md)")
# Allow-list: a token is not checked when it contains a placeholder or glob, or starts with
# a generated, untracked or external prefix.
PLACEHOLDER = re.compile(r"NNN|<[^>]*>|[*{}]|\.\.\.|^https?:")
SKIP_PREFIXES = (
    "_build/", "_site/",                    # generated (AGENTS.md "Generated files")
    "model_v1/OUTPUTS/",                    # generated
    "registry/anchors.yml", "registry/crosslinks.json",   # generated by the crosslink workflow
    "registry/references.json",             # generated by pipeline/bib_to_json.py, gitignored
    "Tools/",                               # the author's own folder, not in the repo
)
NOT_GUIDES = {"README.md", "change-report.md", "handover.md", "brief-template.md", "overview-maintenance.md"}


def files(root: Path) -> list[Path]:
    return sorted({p for pat in SCAN for p in root.glob(pat) if p.is_file()})


def path_like(tok: str) -> bool:
    return "/" in tok and (tok.endswith("/") or tok.endswith(EXTS))


def exists(root: Path, src: Path, tok: str) -> bool:
    tok = re.split(r"[#:]", tok, maxsplit=1)[0] if not tok.endswith("/") else tok
    return any((base / tok).exists() for base in (root, src.parent))


def check(root: Path) -> list[str]:
    out: list[str] = []
    for src in files(root):
        rel = src.relative_to(root).as_posix()
        text = src.read_text(encoding="utf-8")
        for n, line in enumerate(text.splitlines(), 1):
            for target in LINK.findall(line):                                  # rule 1
                if target.startswith(("http", "mailto:", "#")):
                    continue
                if not (src.parent / target.split("#")[0]).exists():
                    out.append(f"{rel}:{n} broken link {target}")
            for tok in TICK.findall(line):                                     # rule 2
                if not path_like(tok) or PLACEHOLDER.search(tok) or tok.startswith(SKIP_PREFIXES):
                    continue
                if not exists(root, src, tok):
                    out.append(f"{rel}:{n} named path does not exist: {tok}")
        if src.name == "SKILL.md":                                             # rule 3
            if "AGENTS.md" not in text:
                out.append(f"{rel}:1 skill does not name AGENTS.md")
            guides = [g for g in GUIDE.findall(text) if g not in NOT_GUIDES]
            if not guides:
                out.append(f"{rel}:1 skill names no docs/agents guide")
            for g in guides:
                if not (root / "docs" / "agents" / g).is_file():
                    out.append(f"{rel}:1 guide docs/agents/{g} does not exist")
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--root", type=Path, default=Path(__file__).resolve().parent.parent)
    findings = check(ap.parse_args(argv).root)
    print("\n".join(findings))
    return 1 if findings else 0


if __name__ == "__main__":
    sys.exit(main())
