"""
check_agent_docs.py: fail on a broken link or named path in the agent guides (brief 075c).

    python -I project/tools/check_agent_docs.py [--root DIR]

Scans AGENTS.md, project/START_HERE.md, project/agents/*.md and .claude/skills/*/SKILL.md.
Rules
 1. A markdown link [text](path) must resolve relative to the file that holds it
    (the guides write reference/... relative to project/agents/). http, mailto and
    pure #anchor links are skipped; for path#anchor only the file is checked.
 2. A backticked token that looks like a repo path (has a "/" and a known
    extension, or ends in "/") must exist, from the repo root or from the file's
    own folder, unless it is on the allow-list below.
 3. Each .claude/skills/<role>/SKILL.md names AGENTS.md and a project/agents guide,
    and that guide exists.
One line per finding, `file:line message`; exit 1 if any. Standard library only.
Warning (never an error, brief 130c): a binary under data/ or literature/ (pdf, docx, pptx, xlsx, xls, ods, rtf, html)
without its reading copy literature/readable/<path>.md (see project/tools/to_markdown.py copy_path) is listed on stderr as `warning: ...`.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_lane_plan  # noqa: E402  (brief 184c: the open briefs' header lines are parsed by the same code that builds the lane plan)

SCAN = ("AGENTS.md", "project/START_HERE.md", "project/agents/*.md", ".claude/skills/*/SKILL.md")
EXTS = (".md", ".py", ".toml", ".json", ".yml", ".yaml", ".html", ".bib", ".skill", ".qmd")
LINK = re.compile(r"\[[^\]]*\]\(([^)\s]+)\)")
TICK = re.compile(r"`([^`\s]+)`")
GUIDE = re.compile(r"project/agents/([\w.-]+\.md)")
# Allow-list: a token is not checked when it contains a placeholder or glob, or starts with
# a generated, untracked or external prefix.
PLACEHOLDER = re.compile(r"NNN|<[^>]*>|[*{}]|\.\.\.|^https?:")
SKIP_PREFIXES = (
    "_build/", "_site/",                    # generated (AGENTS.md "Generated files")
    "model_v1/OUTPUTS/",                    # generated
    "website/registry/anchors.yml", "website/registry/crosslinks.json",   # generated by the crosslink workflow
    "literature/references.json",             # generated by website/build/bib_to_json.py, gitignored
    "Tools/",                               # the author's own folder, not in the repo
)
BINARY = (".pdf", ".docx", ".pptx", ".xlsx", ".xls", ".ods", ".rtf", ".html", ".htm")       # as project/tools/to_markdown.py
NOT_GUIDES = {"README.md", "change-report.md", "handover.md", "brief-template.md", "overview-maintenance.md"}


def files(root: Path) -> list[Path]:
    return sorted({p for pat in SCAN for p in root.glob(pat) if p.is_file()})


def path_like(tok: str) -> bool:
    return "/" in tok and (tok.endswith("/") or tok.endswith(EXTS))


def exists(root: Path, src: Path, tok: str) -> bool:
    tok = re.split(r"[#:]", tok, maxsplit=1)[0] if not tok.endswith("/") else tok
    return any((base / tok).exists() for base in (root, src.parent))


def check(root: Path) -> list[str]:
    out: list[str] = []
    for src in files(root):
        rel = src.relative_to(root).as_posix()
        text = src.read_text(encoding="utf-8")
        for n, line in enumerate(text.splitlines(), 1):
            for target in LINK.findall(line):                                  # rule 1
                if target.startswith(("http", "mailto:", "#")):
                    continue
                if not (src.parent / target.split("#")[0]).exists():
                    out.append(f"{rel}:{n} broken link {target}")
            for tok in TICK.findall(line):                                     # rule 2
                if not path_like(tok) or PLACEHOLDER.search(tok) or tok.startswith(SKIP_PREFIXES):
                    continue
                if not exists(root, src, tok):
                    out.append(f"{rel}:{n} named path does not exist: {tok}")
        if src.name == "SKILL.md":                                             # rule 3
            if "AGENTS.md" not in text:
                out.append(f"{rel}:1 skill does not name AGENTS.md")
            guides = [g for g in GUIDE.findall(text) if g not in NOT_GUIDES]
            if not guides:
                out.append(f"{rel}:1 skill names no project/agents guide")
            for g in guides:
                if not (root / "project" / "agents" / g).is_file():
                    out.append(f"{rel}:1 guide project/agents/{g} does not exist")
    if (root / "project" / "briefs" / "open").is_dir():                         # rule 4 (184c): header lines of the open briefs
        out += build_lane_plan.problems(root)
    return out


def missing_copies(root: Path) -> list[str]:
    """Binary files under data/ and literature/ with no reading copy (`python -I project/tools/to_markdown.py --readable <file>` makes it). Same rule as to_markdown.copy_path."""
    def copy(rel: Path) -> Path:
        rel = Path(*rel.parts[1:]) if rel.parts[0] == "literature" else rel
        return root / "literature" / "readable" / (rel.as_posix() + ".md")
    skip = root / "literature" / "readable"
    found = [p for d in ("data", "literature") if (root / d).is_dir() for p in sorted((root / d).rglob("*"))
             if p.is_file() and p.suffix.lower() in BINARY and skip not in p.parents]
    return [f"warning: no reading copy for {p.relative_to(root).as_posix()} (python -I project/tools/to_markdown.py --readable <file>)"
            for p in found if not copy(p.relative_to(root)).is_file()]


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[2])
    root = ap.parse_args(argv).root
    findings = check(root)
    print("\n".join(findings))
    for w in missing_copies(root):
        print(w, file=sys.stderr)
    return 1 if findings else 0


if __name__ == "__main__":
    sys.exit(main())
