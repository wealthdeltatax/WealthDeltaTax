#!/usr/bin/env python3
"""Brief 175r: the retired-tax series as a share of GDP, 1978-79 to 2027-28, from the held IFS workbook.

    python -I research/tables/174r-evidence/retired_tax_series.py

Reads `data/rates/Revenue composition spreadsheet.xlsx` (IFS, "Composition of UK revenue"; read only) and writes, next to this script,
  retired-tax-gdp-annual-full.csv   one row per tax, basis and year: share of GDP in percent (four decimals), outturn or forecast flag (the sheet's own row 2
                                    label), sheet, cell row, the sheet's row label, the file path, and the sheet's own footnotes for the row;
  retired-tax-overlap-174r.csv      every value of the 174r partial series that the workbook also holds (OBR WP15 2007-08 to 2018-19, EFO 2024-25, HMRC bulletin 2006-07 and 2025-26) against the workbook on both bases, with the difference in points.
The two files are regenerated byte for byte (fixed order, fixed rounding, no dates). Prints one summary line.
Sheets: `% GDP (cash)` (1978-79 to 2027-28; labels in column A, years in row 3, Outturn or Forecast in row 2) and `% GDP (national accounts)` (1999-00 to 2027-28;
labels in column A, ONS codes in column B, years from column C). Values in the sheets are fractions of GDP; the CSV holds percent.
"""
import csv
import sys
from pathlib import Path

import openpyxl

ROOT = Path(__file__).resolve().parents[3]
HERE = Path(__file__).resolve().parent
XLSX = 'data/rates/Revenue composition spreadsheet.xlsx'
CASH, NA = '% GDP (cash)', '% GDP (national accounts)'
# tax id -> (cash row, national accounts row or None, footnote rows in the cash sheet (note letters, sources), footnote rows in the national accounts sheet)
TAXES = [
    ('corporation_tax', 10, 8, (66, 83), (72,)),
    ('corporation_tax_onshore', 12, 10, (66, 83), (72,)),
    ('capital_gains_tax', 20, 15, (85,), ()),
    ('inheritance_tax', 21, 16, (67, 86), ()),
    ('stamp_duties_total', 22, 17, (87,), ()),
    ('stamp_property_transaction_taxes', 24, 19, (68, 87), (73,)),
    ('stamp_taxes_on_shares', 25, 20, (87,), ()),
    ('business_rates', 52, 36, (96,), (78,)),
    ('council_tax', 53, 37, (72, 96), (79,)),
    ('total_hmrc', 50, None, (), ()),
]
OVERLAP = {                                                          # 174r tax -> tax id here; each 174r value is compared with both bases (percent of GDP, financial years)
    'onshore_corporation_tax': 'corporation_tax_onshore',
    'council_tax_GB': 'council_tax',
    'capital_gains_tax': 'capital_gains_tax',
    'property_transaction_taxes': 'stamp_property_transaction_taxes',
    'business_rates': 'business_rates',                               # 174r: one 2024-25 value (OBR EFO March 2025 Table 4.1)
    'inheritance_tax': 'inheritance_tax',                             # 174r: 2006-07 and 2025-26 (HMRC bulletin, one decimal)
    'stamp_taxes_combined': 'stamp_duties_total',                     # 174r: 2006-07 and 2025-26 (HMRC bulletin, one decimal)
}


def text(cell):
    return ' '.join(str(cell).split()) if cell is not None else ''


def read(ws, label_row_flags=2, year_row=3, first_col=2):
    """{col: (year, flag)} for the year columns of a sheet."""
    cols = {}
    for c in range(first_col, ws.max_column + 1):
        y = ws.cell(year_row, c).value
        if isinstance(y, str) and len(y) == 7 and y[4] == '-':
            cols[c] = (y, str(ws.cell(label_row_flags, c).value).strip().lower())
    return cols


def build():
    wb = openpyxl.load_workbook(ROOT / XLSX, data_only=True)
    cash, na = wb[CASH], wb[NA]
    cols = {'cash': read(cash), 'national_accounts': read(na)}
    sheets = {'cash': cash, 'national_accounts': na}
    out = []
    for tax, crow, nrow, cnotes, nnotes in TAXES:
        for basis, row, notes in (('cash', crow, cnotes), ('national_accounts', nrow, nnotes)):
            if row is None:
                continue
            ws = sheets[basis]
            label = text(ws.cell(row, 1).value)
            note = ' | '.join(text(ws.cell(r, 1).value) for r in notes)
            for c, (year, flag) in cols[basis].items():
                v = ws.cell(row, c).value
                if v is None or v == '':
                    continue                                          # the sheet leaves a component blank before it exists (stamp components before 1999-00)
                out.append([tax, year, basis, f'{100 * float(v):.4f}', flag, ws.title, row, label, XLSX, note])
    return out


def overlap(rows):
    have = {(r[0], r[1], r[2]): r for r in rows}
    old = list(csv.DictReader((HERE / 'retired-tax-gdp-annual.csv').open(encoding='utf-8')))
    out = []
    for r in old:
        if r['tax'] not in OVERLAP or r['receipts_percent_GDP'] == '':
            continue
        for basis in ('cash', 'national_accounts'):
            tax = OVERLAP[r['tax']]
            w = have.get((tax, r['financial_year'], basis))
            if w is None:
                continue
            d = float(w[3]) - float(r['receipts_percent_GDP'])
            out.append([r['tax'], r['financial_year'], r['receipts_percent_GDP'], r['source'], w[3], tax, basis, f'{d:+.4f}', 'yes' if abs(d) > 0.1 else 'no'])
    return out


def write(path, header, rows):
    with path.open('w', newline='', encoding='utf-8') as fh:
        w = csv.writer(fh, lineterminator='\n')
        w.writerow(header)
        w.writerows(rows)


def main():
    rows = build()
    write(HERE / 'retired-tax-gdp-annual-full.csv', ['tax', 'financial_year', 'basis', 'receipts_percent_GDP', 'flag', 'sheet', 'row', 'row_label', 'source_file', 'sheet_notes'], rows)
    ov = overlap(rows)
    write(HERE / 'retired-tax-overlap-174r.csv', ['tax_174r', 'financial_year', 'value_174r', 'source_174r', 'value_workbook', 'tax_workbook', 'basis', 'difference_points', 'above_0.1'], ov)
    print(f'{len(rows)} rows, {len({r[0] for r in rows})} series, {sum(r[4] == "forecast" for r in rows)} forecast rows; overlap {len(ov)} comparisons, {sum(o[-1] == "yes" for o in ov)} differ by more than 0.1 point')
    return 0


if __name__ == '__main__':
    sys.exit(main())
