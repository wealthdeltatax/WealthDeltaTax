@pytest.fixture(scope="module")
def real():
    rows = cfg.load_pages()
    return rows, R.load_routing(), R.spoke_infos(rows)[0]


def test_real_navbar_has_five_items_and_fifteen_questions(real):
    rows, _, infos = real
    items = nav.navbar(rows, infos)
    assert top_texts(items) == ["Questions", "Data", "Papers", "Resources", "About"]
    q = sub(items, "Questions")
    menu = sorted((r for r in rows if r["type"] == "spoke" and r["order"] is not None), key=lambda r: r["order"])
    assert len(q) == 15 and [m["id"] for m in q] == [r["id"] for r in menu]
    assert [m["text"].split(" (draft)")[0] for m in q] == [f"{r['id']} {r['label']}" for r in menu]
    banned = {r["id"] for r in rows if r["type"] in ("appendix", "pending", "calculator", "standalone", "site", "legacy")}
    assert not {m["id"] for m in q} & banned


def test_real_resources_hold_the_pending_pages_and_calculators(real):
    rows, _, infos = real
    res = sub(nav.navbar(rows, infos), "Resources")
    ids = [m.get("id") for m in res]
    for r in rows:
        if r["type"] in ("pending", "calculator"):
            assert r["id"] in ids, r["id"]
    assert sum(1 for r in rows if r["type"] == "pending") == 10
    assert sum(1 for r in rows if r["type"] == "calculator") == 3
    assert nav.PENDING_HEADING in [m["text"] for m in res]


def test_real_registry_is_reachable_within_two_clicks(real):
    rows, routes, infos = real
    res = nav.reachability(rows, routes, infos)
    assert res["ok"], res
    must = [r["id"] for r in rows if r["id"] not in res["exempt"]]
    assert all(res["depth"][i] <= 2 for i in must)
    assert all(res["depth"][f"DL{n}"] == 1 for n in range(7))
    appendices = [r["id"] for r in rows if r["type"] == "appendix"]
    assert len(appendices) == 7 and all(res["depth"][a] == 2 for a in appendices)
    assert res["checked"] == 51


def test_real_exemptions_are_the_listed_ones(real):
    rows, routes, infos = real
    ex = nav.reachability(rows, routes, infos)["exempt"]
    assert {i for i in ex if not i.startswith("old-")} == {"HOME", "CORPUS", "E404"}
    assert sum(1 for i in ex if i.startswith("old-")) == 30


def test_the_cli_writes_the_fragment_and_passes(tmp_path):
    out = tmp_path / "navbar.generated.yml"
    assert nav.main(["--write", str(out)]) == 0
    assert len(yaml.safe_load(out.read_text(encoding="utf-8"))["website"]["navbar"]["left"]) == 5
