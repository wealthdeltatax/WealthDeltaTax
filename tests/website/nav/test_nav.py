def top_texts(items):
    return [i["text"] for i in items]


def sub(items, name):
    return next(i for i in items if i["text"] == name)["menu"]


# ── navbar structure ──────────────────────────────────────────────────────────

def test_navbar_has_exactly_five_items(rows, infos):
    assert top_texts(nav.navbar(rows, infos)) == ["Questions", "Data", "Papers", "Resources", "About"]


def test_questions_are_the_menu_spokes_in_order_with_labels(rows, infos):
    q = sub(nav.navbar(rows, infos), "Questions")
    assert [m["id"] for m in q] == ["FAIR", "MECH", "VAL", "FISC"]
    assert q[0]["text"].startswith("FAIR Fairness") and q[3]["text"].startswith("FISC Rates and revenue")
    assert [m["href"] for m in q] == ["fair.html", "mech.html", "val.html", "fisc.html"]


def test_order_field_sets_menu_order(rows, infos):
    rows = copy.deepcopy(rows)
    next(r for r in rows if r["id"] == "FISC")["order"] = 0
    assert [m["id"] for m in sub(nav.navbar(rows, infos), "Questions")][0] == "FISC"


def test_no_appendix_pending_or_data_page_in_questions(rows, infos):
    ids = {m["id"] for m in sub(nav.navbar(rows, infos), "Questions")}
    assert not ids & {"DECL", "FAQ", "TAXCALC", "ADD", "DL0", "REFS"}


def test_data_menu_is_dl0_to_dl6(rows, infos):
    d = sub(nav.navbar(rows, infos), "Data")
    assert [m["id"] for m in d] == [f"DL{i}" for i in range(7)]
    assert d[0]["href"] == "data.html" and d[2]["href"] == "data/inputs.html"


def test_papers_menu_holds_the_standalone_papers(rows, infos):
    assert [m["id"] for m in sub(nav.navbar(rows, infos), "Papers")] == ["ADD"]


def test_resources_hold_utility_calculators_and_a_pending_group(rows, infos):
    res = sub(nav.navbar(rows, infos), "Resources")
    texts = [m["text"] for m in res]
    assert [m.get("id") for m in res[:3]] == ["REFS", "GLOSS", "RET"]
    assert nav.CALC_HEADING in texts and nav.PENDING_HEADING in texts
    calc = texts.index(nav.CALC_HEADING)
    pend = texts.index(nav.PENDING_HEADING)
    assert [m["id"] for m in res[calc + 1:pend]] == ["CALCIDX", "TAXCALC"]
    assert [m["id"] for m in res[pend + 1:]] == ["FAQ"]
    assert "Based on the retired model".lower() in nav.CALC_HEADING.lower()


def test_about_is_a_plain_link(rows, infos):
    about = nav.navbar(rows, infos)[-1]
    assert about == {"text": "About", "href": "author_page.html", "id": "ABOUT"}


def test_fragment_moves_search_to_the_navbar_and_drops_ids(rows, infos):
    frag = nav.navbar_fragment(rows, infos)
    assert frag["website"]["search"] == {"location": "navbar", "type": "textbox"}
    left = frag["website"]["navbar"]["left"]
    assert len(left) == 5 and "id" not in yaml.safe_dump(left)
    assert frag == yaml.safe_load(yaml.safe_dump(frag))              # plain data, round-trips


def test_write_fragment_makes_a_yaml_file(rows, tmp_path):
    out = nav.write_navbar_fragment(tmp_path / "sub" / "navbar.generated.yml", rows)
    text = out.read_text(encoding="utf-8")
    assert text.startswith("# Generated by pipeline/pages/nav.py")
    assert len(yaml.safe_load(text)["website"]["navbar"]["left"]) == 5


# ── the draft mark ────────────────────────────────────────────────────────────

def test_draft_mark(rows, infos):
    assert nav.is_draft(infos["VAL"]) is True                        # status: draft
    assert nav.is_draft(infos["FISC"]) is False                      # status: accepted
    assert nav.is_draft(infos["FAIR"]) is True                       # no file: draft
    by = {r["id"]: r for r in rows}
    assert nav.menu_text(by["VAL"], infos["VAL"]) == "VAL Valuation (draft)"
    assert nav.menu_text(by["FISC"], infos["FISC"]) == "FISC Rates and revenue"


def test_navbar_marks_only_unaccepted_spokes(rows, infos):
    q = {m["id"]: m["text"] for m in sub(nav.navbar(rows, infos), "Questions")}
    assert q["FAIR"].endswith("(draft)") and q["VAL"].endswith("(draft)")
    assert not q["MECH"].endswith("(draft)") and not q["FISC"].endswith("(draft)")
    plain = {m["id"]: m["text"] for m in sub(nav.navbar(rows, infos, mark_drafts=False), "Questions")}
    assert not any("(draft)" in t for t in plain.values())


