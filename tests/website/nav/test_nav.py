# ── the search description ────────────────────────────────────────────────────

def test_description_is_question_plus_first_sentence(infos):
    d = nav.search_description(infos["FISC"])
    assert d == ("What rate, what threshold, how much? "
                 "The tax raises a modest share of GDP at the central schedule.")
    assert len(d) <= 155


def test_description_without_a_short_answer_is_the_question():
    assert nav.search_description({"question": "Is it fair?", "short_answer": ""}) == "Is it fair?"


def test_description_never_exceeds_155_characters():
    info = {"question": "Q" * 40, "short_answer": " ".join(["word"] * 80) + "."}
    d = nav.search_description(info)
    assert len(d) <= 155 and d.endswith("…")
    assert d.startswith("Q" * 40 + " word")


def test_description_at_exactly_the_limit_is_kept_whole():
    q = "Q" * 100                                       # 100 + 1 + 54 = 155 characters exactly
    info = {"question": q, "short_answer": "x" * 53 + ". More text follows."}
    d = nav.search_description(info)
    assert len(d) == 155 and not d.endswith("…")


def test_description_cuts_at_a_word_boundary():
    info = {"question": "Short question?", "short_answer": "A " + "longword " * 30 + "end."}
    d = nav.search_description(info)
    assert len(d) <= 155 and d.endswith("…") and not d[:-1].endswith("longwor")


# ── reachability (nav.md section 9) ───────────────────────────────────────────

def test_fixture_registry_is_within_two_clicks(rows, routes, infos):
    res = nav.reachability(rows, routes, infos)
    assert res["ok"] and res["too_far"] == [] and res["unreachable"] == []
    assert res["depth"]["H"] == 0
    assert res["depth"]["FISC"] == 1 and res["depth"]["DL0"] == 1 and res["depth"]["FAQ"] == 1
    assert res["depth"]["DECL"] == 2                                  # hub, parent, appendix
    assert "E404" in res["exempt"]                                    # listed, with a reason


def test_a_page_three_clicks_away_fails(rows, routes, infos):
    rows = copy.deepcopy(rows)
    rows.append({**next(r for r in rows if r["id"] == "DECL"), "id": "DEEP", "url": "/deep.html", "parent": "DECL"})
    res = nav.reachability(rows, routes, infos)
    assert not res["ok"] and res["too_far"] == ["DEEP"] and res["depth"]["DEEP"] == 3


def test_an_unlinked_page_is_unreachable(rows, routes, infos):
    rows = copy.deepcopy(rows)
    rows.append({**next(r for r in rows if r["id"] == "FAQ"), "id": "LOST", "type": "site", "url": "/lost.html"})
    res = nav.reachability(rows, routes, infos)
    assert not res["ok"] and res["unreachable"] == ["LOST"]


def test_a_page_linked_only_by_a_route_is_reachable(rows, routes, infos):
    rows = copy.deepcopy(rows)
    rows.append({**next(r for r in rows if r["id"] == "DECL"), "id": "SIDE", "url": "/side.html", "parent": None})
    routes = copy.deepcopy(routes)
    routes[0]["start"].append("SIDE")                                 # a card links it: one click
    assert nav.reachability(rows, routes, infos)["depth"]["SIDE"] == 1


def test_exempt_pages_are_listed_not_checked(rows, routes, infos):
    rows = copy.deepcopy(rows)
    rows.append({**next(r for r in rows if r["id"] == "FAQ"), "id": "old-x", "type": "legacy", "url": "/x.html"})
    res = nav.reachability(rows, routes, infos)
    assert res["ok"] and "old-x" in res["exempt"]


def test_no_hub_is_an_error(rows, routes, infos):
    with pytest.raises(ValueError):
        nav.reachability([r for r in rows if r["type"] != "hub"], routes, infos)


