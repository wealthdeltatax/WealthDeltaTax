"""website/registry/pages.yml and the loader (brief 029s)."""
import copy
from collections import Counter

import pytest
import yaml

import config as cfg
from conftest import FIXTURES, ROOT


@pytest.fixture(scope="module")
def pages():
    return cfg.load_pages()


def fixture_rows():
    return cfg.load_pages(FIXTURES / "pages_ok.yml")


# ── the real registry ─────────────────────────────────────────────────────────

def test_real_registry_is_valid(pages):
    assert cfg.validate_pages(pages) == []


def test_one_row_per_page_named_in_the_brief(pages):
    n = Counter(r["type"] for r in pages)
    assert n["legacy"] + n["standalone"] == 33          # the 33 old papers
    assert n["standalone"] == 3                         # ADD, INST, SCOPE
    assert n["spoke"] + n["appendix"] == 22             # the new spokes
    assert (n["spoke"], n["appendix"]) == (15, 7)
    assert n["hub"] == 1
    assert n["pending"] == 10
    assert n["calculator"] == 3
    ids = {r["id"] for r in pages}
    assert {"ADD", "INST", "SCOPE", "H", "REFS", "GLOSS", "RET", "ABOUT", "E404", "CALCIDX"} <= ids


def test_menu_has_orders_1_to_15(pages):
    assert sorted(r["order"] for r in pages if r["order"] is not None) == list(range(1, 16))
    assert all(r["label"] for r in pages if r["order"] is not None)


def test_legacy_rows_match_papers_yml(pages):
    """papers.yml stays the legacy source until cutover; the two must not drift."""
    papers = yaml.safe_load((ROOT / "website" / "registry" / "papers.yml").read_text(encoding="utf-8"))
    want = {(p["source"], p["output"]) for p in papers}
    got = {(e["source"], e["output"]) for e in cfg.paper_registry(pages)}
    assert got == want and len(papers) == 33


# generated by the build and git-ignored, so absent from a fresh checkout
GENERATED_SOURCES = {"website/site/pages/glossary.md"}


def test_every_live_source_path_exists(pages):
    for r in pages:
        if r["source"] and r["status"] in cfg.LIVE_STATUSES and r["source"] not in GENERATED_SOURCES:
            assert (ROOT / r["source"]).exists(), f"{r['id']}: {r['source']}"


def test_real_collisions_are_the_known_set(pages):
    """New codes reuse old URLs (site.md Q1); each is reported and the live row wins."""
    got = {c["url"]: (c["live"], c["held"]) for c in cfg.find_url_collisions(pages)}
    assert got == {
        "/behav.html": (["old-behav"], ["BEHAV"]),
        "/corp.html":  (["old-corp"], ["CORP"]),
        "/gov.html":   (["old-gov"], ["GOV"]),
        "/index.html": (["HOME"], ["H"]),
        "/pol.html":   (["old-pol"], ["POL"]),
        "/val.html":   (["old-val"], ["VAL"]),
        "/wp.html":    (["old-wp"], ["H"]),
    }
    assert all(len(live) == 1 for live, _ in got.values())   # never two live rows


def test_held_rows_are_not_built(pages):
    built = {e["output"] for e in cfg.paper_registry(pages)}
    assert "val.qmd" in built                      # the old paper
    assert len(built) == 33


# ── validation on fixtures ────────────────────────────────────────────────────

def test_fixture_is_valid():
    assert cfg.validate_pages(fixture_rows()) == []


def test_duplicate_id_is_an_error():
    rows = fixture_rows()
    rows.append(copy.deepcopy(rows[0]))
    assert any("duplicate id" in e for e in cfg.validate_pages(rows))


def test_missing_parent_is_an_error():
    rows = fixture_rows()
    next(r for r in rows if r["id"] == "DECL")["parent"] = "NOPE"
    assert any("DECL" in e and "does not exist" in e for e in cfg.validate_pages(rows))


def test_appendix_parent_must_be_a_menu_spoke():
    rows = fixture_rows()
    next(r for r in rows if r["id"] == "DECL")["parent"] = "H"
    assert any("must be a menu spoke" in e for e in cfg.validate_pages(rows))


def test_spoke_row_must_not_set_title_or_status():
    rows = fixture_rows()
    v = next(r for r in rows if r["id"] == "VAL")
    v["title"], v["status"] = "T", "draft"
    errs = cfg.validate_pages(rows)
    assert any("must not set title" in e for e in errs)
    assert any("must not set status" in e for e in errs)


def test_non_spoke_row_needs_title_and_valid_status():
    rows = fixture_rows()
    rows[0]["title"] = None
    rows[1]["status"] = "published"
    errs = cfg.validate_pages(rows)
    assert any("old-val: no title" in e for e in errs)
    assert any("old-wp: status" in e for e in errs)


def test_duplicate_menu_order_is_an_error():
    rows = fixture_rows()
    next(r for r in rows if r["id"] == "FISC")["order"] = 1
    assert any("order 1 also used" in e for e in cfg.validate_pages(rows))


# ── URL collisions on fixtures: reported, not published ───────────────────────

def test_legacy_vs_new_collision_is_reported_and_held():
    rows = fixture_rows()
    c = {c["url"]: c for c in cfg.find_url_collisions(rows)}
    assert c["/val.html"]["live"] == ["old-val"]
    assert c["/val.html"]["held"] == ["VAL"]
    assert c["/wp.html"]["held"] == ["H"]          # a hub alias counts as a claim


def test_colliding_new_row_is_never_in_the_build_list():
    rows = fixture_rows()
    # a new row that is a paper row on a live URL must be held out
    rows.append({**rows[0], "id": "VAL-NEW", "status": "draft", "source": "papers/legacy/other.md"})
    out = [e["source"] for e in cfg.paper_registry(rows)]
    assert "other.md" not in out
    assert "5_Valuing_Wealth.md" in out


def test_two_live_rows_on_one_url_are_flagged():
    rows = fixture_rows()
    rows.append({**rows[0], "id": "old-val-2"})
    c = {c["url"]: c for c in cfg.find_url_collisions(rows)}
    assert len(c["/val.html"]["live"]) == 2
